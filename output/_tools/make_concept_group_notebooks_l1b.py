# traceback 构造（真实 IPython 格式，实测于 IPython 9.17.1）
# ---------------------------------------------------------------------------
TB_SEP = "-" * 75
TB_PAD = 41          # 异常名左对齐补空格到这个宽度，'Traceback' 便落在第 42 列


def tb(ename, cell_no, line_no, src_line, message):
    hdr = ename.ljust(TB_PAD) + " " + "Traceback (most recent call last)"
    return "\n".join([
        TB_SEP,
        hdr,
        "Cell In[%d], line %d" % (cell_no, line_no),
        "----> %d %s" % (line_no, src_line),
        "",
        "%s: %s" % (ename, message),
    ])


def fence(block):
    return "```\n" + block + "\n```"


def out_block(text):
    """markdown 里的「预期输出」代码块。"""
    return fence(text.strip("\n"))


def err_line_no(src, marker):
    """从被注释掉的报错行里取出(真实行号, 去掉注释的源码)，避免手数行号出错。"""
    for i, line in enumerate(src.strip("\n").split("\n")):
        bare = line.lstrip("#").strip()
        if bare.startswith(marker):
            return i + 1, bare
    raise ValueError("未找到被注释的报错行: %r" % marker)


